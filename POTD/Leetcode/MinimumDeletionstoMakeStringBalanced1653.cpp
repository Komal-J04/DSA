// APPROACH 2 - count the no. of b's, and if an 'a' is encountered and there was a 'b' before it(i.e, count > 0) then decrement count and increment the final answer
class Solution
{
public:
    int minimumDeletions(string s)
    {
        int ans = 0, count = 0, n = s.size();

        for (int i = 0; i < n; i++)
        {
            if (s[i] == 'b')
                count++;
            else if (count)
            {
                ans++;
                count--;
            }
        }

        return ans;
    }
};

