// APPROACH 3 - USING 'A' COUNT & 'B' COUNT
class Solution
{
public:
    int minimumDeletions(string s)
    {
        int acnt = 0, bcnt = 0, ans = INT_MAX;
        for (auto c : s)
            acnt += (c == 'a');
        for (auto c : s)
        {
            acnt -= (c == 'a');
            ans = min(ans, acnt + bcnt);
            bcnt += (c == 'b');
        }
        return ans;
    }
};