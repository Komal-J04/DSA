// APPROACH 1

class Solution
{
public:
    int countSeniors(vector<string> &details)
    {
        int cnt = 0, n = details.size();
        for (int i = 0; i < n; i++)
        {
            if ((((details[i][11] - 48) * 10) + (details[i][12] - 48)) > 60)
                cnt++;
        }
        return cnt;
    }
};

