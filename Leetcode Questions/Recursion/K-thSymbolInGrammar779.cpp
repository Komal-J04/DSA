// APPROACH 1 - NAIVE (TLE)

class Solution
{
public:
    int kthGrammar(int n, int k)
    {
        vector<string> ranks(n + 1);
        ranks[1] = "0";
        for (int i = 2; i <= n; i++)
        {
            string prev = ranks[i - 1];
            string temp = "";
            for (auto x : prev)
            {
                if (x == '0')
                    temp += "01";
                else
                    temp += "10";
            }
            ranks[i] = temp;
        }
        return (ranks[n][k - 1] - 48);
    }
};

