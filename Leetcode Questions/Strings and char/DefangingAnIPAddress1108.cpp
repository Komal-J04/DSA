// APPROACH 2 - NEW STRING
class Solution
{
public:
    string defangIPaddr(string address)
    {
        string defang = "";
        for (char x : address)
        {
            if (x != '.')
                defang += x;
            else
            {
                defang += "[.]";
            }
        }

        return defang;
    }
};